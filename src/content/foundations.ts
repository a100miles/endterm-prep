export const foundationModules: Module[] = syllabus.map(
  ([short, title, slides, rows], index) => {
    const id = 101 + index;
    return {
      id,
      short,
      title,
      slides,
      file: `AcademyCloudFoundations_Module_${String(index + 1).padStart(2, "0")}${[3, 4, 6].includes(index + 1) ? " (1)" : ""}.pptx`,
      description: rows.map(([title]) => title).join(" · "),
      topics: rows.map(
        (
          [title, slides, explanation, example, exam, correct],
          topic,
        ): Topic => ({
          id: `${id}-${topic + 1}`,
          title,
          slides,
          explanation,
          example,
          exam,
          definition: explanation.split(". ")[0].replace(/\.$/, "") + ".",
          takeaways: [correct],
          misconception: "",
          terms: [correct, title],
        }),
      ),
    };
  },
);

export const foundationPractice: Question[] = syllabus.flatMap(
  ([, , , rows], index) =>
    rows.map(
      ([, slides, explanation, , prompt, correct, ...distractors], topic) => {
        const module = 101 + index;
        const options = [correct, ...distractors];
        const offset = (index + topic) % options.length;
        return {
          id: `cf-practice-${index + 1}-${topic + 1}`,
          module,
          topic: `${module}-${topic + 1}`,
          prompt,
          options: [...options.slice(offset), ...options.slice(0, offset)],
          answer: [correct],
          explanation,
          source: "Lecture-Based",
          reference: `Cloud Foundations M${index + 1}, slides ${slides}`,
          type: "single",
          difficulty: "Medium",
        };
      },
    ),
);
export function moduleNumber(id: number) {
  return id >= 101 ? id - 100 : id;
}
export function moduleLabel(id: number) {
  return `${id >= 101 ? "Foundations" : "Developing"} ${moduleNumber(id)}`;
}
export function topicModule(id: string) {
  return Number(id.split("-")[0]);
}
